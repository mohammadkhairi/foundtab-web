import { useQuery } from '@tanstack/react-query'
import { useAuth } from '../../../hooks/useAuth'
import { apiFetch } from '../../../lib/api'
import LoadingSpinner from '../../../components/LoadingSpinner'
import ErrorState from '../../../components/ErrorState'
import { env } from '../../../config/env'

type Invoice = {
  id: string
  invoiceNumber: string
  amount: string
  currency: string
  status: 'PENDING' | 'PAID' | 'VOID'
  description: string | null
  periodStart: string | null
  periodEnd: string | null
  dueDate: string | null
  paidAt: string | null
  createdAt: string
}

const STATUS_STYLES: Record<string, { bg: string; text: string; label: string }> = {
  PENDING: { bg: 'bg-amber-100', text: 'text-amber-700', label: 'Pending' },
  PAID:    { bg: 'bg-green-100', text: 'text-green-700', label: 'Paid' },
  VOID:    { bg: 'bg-gray-100',  text: 'text-gray-500',  label: 'Void' },
}

function fmt(iso: string | null): string {
  if (!iso) return '—'
  return new Date(iso).toLocaleDateString('en-MY', { day: 'numeric', month: 'short', year: 'numeric' })
}

export default function InvoiceListPage() {
  const { token } = useAuth()

  const { data: invoices, isLoading, isError } = useQuery({
    queryKey: ['invoices'],
    queryFn: () => apiFetch<Invoice[]>('/api/v1/invoices', { token }),
    enabled: !!token,
  })

  async function downloadPdf(invoice: Invoice) {
    const res = await fetch(`${env.VITE_API_URL}/api/v1/invoices/${invoice.id}/pdf`, {
      headers: { Authorization: `Bearer ${token}` },
    })
    if (!res.ok) return
    const blob = await res.blob()
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${invoice.invoiceNumber}.pdf`
    a.click()
    URL.revokeObjectURL(url)
  }

  if (isLoading) return <div className="p-6"><LoadingSpinner /></div>
  if (isError) return <div className="p-6"><ErrorState message="Failed to load invoices." /></div>

  return (
    <div className="p-4 md:p-6 max-w-3xl mx-auto">
      <h1 className="text-xl font-bold text-gray-900 mb-5">Invoices</h1>

      {!invoices || invoices.length === 0 ? (
        <div className="bg-white rounded-2xl border border-gray-200 py-16 text-center">
          <p className="text-sm text-gray-400">No invoices yet.</p>
          <p className="text-xs text-gray-400 mt-1">Invoices are generated by FoundTab when your subscription renews.</p>
        </div>
      ) : (
        <div className="bg-white rounded-2xl border border-gray-200 overflow-hidden">
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b border-gray-100 bg-gray-50">
                <th className="px-4 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Invoice</th>
                <th className="px-4 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Amount</th>
                <th className="px-4 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Status</th>
                <th className="px-4 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Due</th>
                <th className="px-4 py-3" />
              </tr>
            </thead>
            <tbody>
              {invoices.map((inv) => {
                const s = STATUS_STYLES[inv.status] ?? STATUS_STYLES.PENDING
                return (
                  <tr key={inv.id} className="border-b border-gray-100 last:border-0">
                    <td className="px-4 py-3">
                      <p className="font-medium text-gray-900">{inv.invoiceNumber}</p>
                      {inv.description && <p className="text-xs text-gray-400 mt-0.5">{inv.description}</p>}
                      {inv.periodStart && inv.periodEnd && (
                        <p className="text-xs text-gray-400">{fmt(inv.periodStart)} – {fmt(inv.periodEnd)}</p>
                      )}
                    </td>
                    <td className="px-4 py-3 font-medium text-gray-900">
                      {inv.currency} {parseFloat(inv.amount).toFixed(2)}
                    </td>
                    <td className="px-4 py-3">
                      <span className={`text-xs font-semibold px-2 py-0.5 rounded-full ${s.bg} ${s.text}`}>
                        {s.label}
                      </span>
                      {inv.paidAt && (
                        <p className="text-xs text-gray-400 mt-0.5">Paid {fmt(inv.paidAt)}</p>
                      )}
                    </td>
                    <td className="px-4 py-3 text-xs text-gray-500">{fmt(inv.dueDate)}</td>
                    <td className="px-4 py-3">
                      <button
                        onClick={() => void downloadPdf(inv)}
                        className="text-xs font-medium text-brand-600 hover:text-brand-800 border border-brand-200 rounded-lg px-2.5 py-1 hover:bg-brand-50 transition-colors"
                      >
                        PDF ↓
                      </button>
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        </div>
      )}
    </div>
  )
}
